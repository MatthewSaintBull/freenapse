//! Golden frames: the exact 91-byte HID buffer every command builder produces,
//! frozen as hex. The builders were verified on the mouse one by one (and
//! against what Synapse 4 sends), so a change to any byte here is a protocol
//! regression unless the hardware said otherwise. When a builder changes on
//! purpose, run
//!
//! ```text
//! cargo test --test golden -- --ignored print_frames --nocapture
//! ```
//!
//! and paste the printed table over `EXPECTED`.

