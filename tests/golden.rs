fn hex(r: &Report) -> String {
    r.to_hid_buffer().iter().map(|b| format!("{b:02x}")).collect()
}

/// Prints the table in the form `EXPECTED` wants.
#[test]
#[ignore]
fn print_frames() {
    for (name, r) in frames() {
        println!("    ({name:?}, \"{}\"),", hex(&r));
    }
}

#[test]
fn every_frame_is_91_bytes_with_a_valid_crc() {
    for (name, r) in frames() {
        let b = r.to_hid_buffer();
        assert_eq!(b.len(), 91, "{name}");
        assert_eq!(b[0], 0, "{name}: report id");
        assert_eq!(b[1], 0, "{name}: status byte of a request");
        assert_eq!(b[89], freenapse::protocol::crc(&b[1..]), "{name}: crc");
        assert_eq!(b[90], 0, "{name}: reserved byte");
        assert_eq!(Report::from_hid_buffer(&b), r, "{name}: round trip");
    }
}

#[test]
fn frames_match_the_frozen_table() {
    let got = frames();
    assert_eq!(got.len(), EXPECTED.len(), "builders added or removed: re-run print_frames and update EXPECTED");
    for ((name, r), (want_name, want_hex)) in got.iter().zip(EXPECTED) {
        assert_eq!(name, want_name, "table order");
        assert_eq!(&hex(r), want_hex, "{name}: frame changed");
    }
}

